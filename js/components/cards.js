const container = document.getElementById('features-container');

// Create modal
const modal = document.createElement('div');
modal.id = 'lessonModal';
modal.className = 'fixed inset-0 hidden bg-black/60 backdrop-blur-sm flex items-center justify-center z-50';
modal.innerHTML = `
  <div class="bg-gradient-to-b from-white to-orange-50 rounded-2xl max-w-xl w-full mx-4 p-8 shadow-2xl relative animate-fadeIn flex flex-col items-center text-center border border-orange-100">
    <button id="closeModal" class="absolute top-4 right-4 text-gray-400 hover:text-orange-600 text-2xl leading-none">&times;</button>
    <div class="w-16 h-16 mb-4 rounded-full bg-orange-100 flex items-center justify-center shadow-inner">
      <svg id="lessonIcon" class="h-8 w-8 text-orange-500" fill="none" stroke="currentColor" viewBox="0 0 24 24"></svg>
    </div>
    <h2 id="lessonTitle" class="text-2xl font-bold mb-3 text-orange-700"></h2>
    <p id="lessonContent" class="text-gray-700 leading-relaxed mb-6 px-2"></p>
    <button id="nextLesson" class="hidden bg-orange-500 hover:bg-orange-600 text-white font-semibold px-6 py-2 rounded-full shadow-md transition-all">Next</button>
  </div>
`;
document.body.appendChild(modal);

// Animation style
const style = document.createElement('style');
style.innerHTML = `
@keyframes fadeIn { from { opacity: 0; transform: translateY(30px); } to { opacity: 1; transform: translateY(0); } }
.animate-fadeIn { animation: fadeIn 0.4s ease-out; }
`;
document.head.appendChild(style);

// Modal elements
const lessonTitle = modal.querySelector('#lessonTitle');
const lessonContent = modal.querySelector('#lessonContent');
const closeModal = modal.querySelector('#closeModal');
const nextLessonBtn = modal.querySelector('#nextLesson');
const lessonIcon = modal.querySelector('#lessonIcon');

let currentLessonIndex = 0;
let activeLessons = [];

// Generate feature cards
features.forEach(f => {
  const card = document.createElement('div');
  card.className = "bg-white hover:shadow-xl transition-all duration-300 border border-gray-200 rounded-xl cursor-pointer hover:-translate-y-1";
  
  card.innerHTML = `
    <div class="p-6">
      <div class="w-12 h-12 rounded-lg bg-orange-100 flex items-center justify-center mb-4">
        <svg class="h-6 w-6 text-orange-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          ${f.icon}
        </svg>
      </div>
      <h3 class="text-lg font-semibold text-gray-900 mb-2">${f.title}</h3>
      <p class="text-gray-600 text-sm">${f.description}</p>
    </div>
  `;

  // Show modal on click
  card.addEventListener('click', () => {
    lessonTitle.textContent = f.title;
    lessonIcon.innerHTML = f.icon;

    // Handle multi-page lessons
    activeLessons = Array.isArray(f.lesson) ? f.lesson : [f.lesson];
    currentLessonIndex = 0;

    lessonContent.textContent = activeLessons[currentLessonIndex];
    nextLessonBtn.classList.toggle('hidden', activeLessons.length <= 1);
    modal.classList.remove('hidden');
  });

  container.appendChild(card);
});

// Handle modal close
closeModal.addEventListener('click', () => modal.classList.add('hidden'));
modal.addEventListener('click', e => { if (e.target === modal) modal.classList.add('hidden'); });

// Next lesson button
nextLessonBtn.addEventListener('click', () => {
  if (currentLessonIndex < activeLessons.length - 1) {
    currentLessonIndex++;
    lessonContent.classList.remove('animate-fadeIn');
    void lessonContent.offsetWidth; // reset animation
    lessonContent.classList.add('animate-fadeIn');
    lessonContent.textContent = activeLessons[currentLessonIndex];
    if (currentLessonIndex === activeLessons.length - 1) {
      nextLessonBtn.textContent = "Done";
    }
  } else {
    modal.classList.add('hidden');
    nextLessonBtn.textContent = "Next";
  }
  
});

